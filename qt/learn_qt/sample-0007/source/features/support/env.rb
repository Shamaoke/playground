
## Настройка окружения Cucumber для сценариев управления Qt-приложением.
## Cucumber загружает этот файл перед остальным вспомогательным кодом
## и определениями шагов. Здесь задаются общие настройки и регистрируются
## хуки подготовки, завершения сценариев и паузы после шагов.

## Подключить библиотеку XML-RPC для обращения к серверу Spix.
## Здесь её модуль `XMLRPC::Config` нужен для настройки разбора ответов ниже;
## объект клиента создаётся в `TestApplication#start` при запуске приложения.
require 'xmlrpc/client'

## Добавить `Step` как единое имя для регистрации определений шагов Cucumber.
## В `status_steps.rb` оно позволяет описывать все шаги одним методом
## вместо отдельных имён `Given`, `When` и `Then`.
Cucumber::Glue::Dsl.alias_adverb('Step')

## Разрешить разбор расширения XML-RPC `<nil/>` как значения Ruby `nil`.
## Такие ответы Spix выдаёт для команд без результата, например `mousePress`.
## По умолчанию разбор этого расширения отключён и приводит к ошибке.
XMLRPC::Config.enable_nil_parser = true

## Перед каждым сценарием создать отдельный объект управления приложением.
## Ссылку сохранить в `@application`, доступной шагам и хукам этого сценария.
## Запуск приложения выполняется позже, в шаге «приложение запущено».
## При ошибке в `start` объект не исчезает и остаётся доступен хуку `After`
## для очистки.
Before do
  @application = TestApplication.new
end

## После каждого сценария, включая неуспешный, вызвать `stop` для очистки.
## Он завершает дочерний процесс и ожидает его окончания, если процесс запускался.
## `&.` пропускает `stop`, если `@application` осталась `nil`, например из-за
## ошибки при инициализации объекта в `Before`.
After do
  @application&.stop
end

## После успешного шага сделать паузу для визуального наблюдения за интерфейсом.
## `STEP_DELAY` задаёт длительность в секундах, включая дробные значения.
## Если переменная не задана, используется `0` — дополнительной паузы нет.
## Пример запуска: `STEP_DELAY=2 bundle exec cucumber`.
AfterStep do
  sleep(Float(ENV.fetch('STEP_DELAY', '0')))
end

