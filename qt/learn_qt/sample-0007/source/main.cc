
/// Учебное приложение Qt Quick для проверки тестовой инфраструктуры.
/// Интерфейс описан встроенной строкой QML, а статусные сообщения предоставляет
/// объект C++ `StatusProvider`, передаваемый корневому элементу интерфейса.
/// В сборке с `BUILD_TESTING` приложение запускает XML-RPC-сервер Spix,
/// позволяющий Ruby-клиенту и сценариям Cucumber управлять интерфейсом.

/// Подключить используемые классы и функции Qt:
/// `QGuiApplication` — графическое приложение и цикл обработки событий;
/// `QQuickView` — окно для отображения интерфейса Qt Quick;
/// `QQmlComponent` — загрузка описания QML и создание объекта компонента;
/// `QVariantMap` — именованные начальные свойства корневого объекта QML;
/// `QVariant` — упаковка указателя на объект C++ для передачи в свойство QML;
/// `QByteArray` — хранение встроенного текста QML в виде последовательности байтов;
/// `QUrl` — адрес компонента QML;
/// `QDebug` — вывод диагностических сообщений через `qWarning()`;
/// `QtQml/qqml.h` — функции регистрации типов C++ в системе типов QML.
#include <QGuiApplication>
#include <QQuickView>
#include <QQmlComponent>
#include <QVariantMap>
#include <QVariant>
#include <QByteArray>
#include <QUrl>
#include <QDebug>
#include <QtQml/qqml.h>

/// Подключить заголовки Spix только при определённом макросе `BUILD_TESTING`.
/// `AnyRpcServer` принимает команды XML-RPC от внешнего тестового клиента,
/// а `QtQmlBot` обеспечивает их выполнение в интерфейсе Qt Quick.
/// Макрос передаётся из CMake для тестовой сборки; в обычной сборке
/// эти заголовки не подключаются и наличие Spix не требуется.
#if defined(BUILD_TESTING)
#include <Spix/AnyRpcServer.h>
#include <Spix/QtQmlBot.h>
#endif

/// Подключить объявление класса `StatusProvider` — поставщика статусных сообщений.
/// Его экземпляр создаётся в C++ и передаётся в QML, где интерфейс вызывает
/// методы `ready()`, `mousePressed()` и `spacePressed()` для получения сообщений.
#include "status_provider.hh"

/// Точка входа: создать приложение Qt, связать объект C++ с интерфейсом QML
/// и показать окно. В тестовой сборке включить управление через Spix.
/// Запустить цикл обработки событий и вернуть результат его завершения.
///
/// @param argc Количество аргументов командной строки, включая имя программы.
/// @param argv Указатель на массив указателей на строки аргументов.
/// @return Код завершения цикла событий Qt или `1`, если корневой объект QML
/// не удалось создать.
auto main(int argc, char** argv) -> int {

  /// Создать единственный объект графического приложения до создания окна.
  /// Конструктор инициализирует взаимодействие Qt с графической системой
  /// и обрабатывает относящиеся к Qt аргументы командной строки.
  /// Объект объявлен первым, чтобы уничтожиться после остальных объектов Qt
  /// при выходе из `main`. Цикл событий будет запущен ниже вызовом `exec()`.
  auto app { QGuiApplication { argc, argv } };

  /// Зарегистрировать класс C++ `StatusProvider` как одноимённый тип QML
  /// в модуле `Sample_0007` версии `1.0`. После импорта модуля этот тип
  /// можно использовать в объявлении свойства корневого элемента.
  /// Создание экземпляров из QML запрещено: объект создаётся в C++
  /// и передаётся при создании корневого элемента через начальные свойства.
  /// Последний аргумент задаёт сообщение об ошибке при попытке создать
  /// `StatusProvider` непосредственно в QML. Регистрация сама объект не создаёт.
  qmlRegisterUncreatableType<StatusProvider>(
    "Sample_0007",
    1, 0,
    "StatusProvider",
    QStringLiteral("StatusProvider cannot be created from QML.")
  );

  /// Создать экземпляр поставщика статусных сообщений в C++.
  /// Его адрес будет передан обязательному свойству `statusProvider` в QML.
  /// Объект объявлен до `view`, чтобы жить дольше окна, его QML-движка
  /// и интерфейса, использующего указатель на поставщика.
  auto statusProvider { StatusProvider { } };

  /// Создать окно `QQuickView`, владеющее собственным движком QML.
  /// Содержимое будет создано отдельно через `QQmlComponent` и установлено
  /// вызовом `setContent()`. Показ окна выполняется ниже через `show()`.
  auto view { QQuickView { } };

  /// Создать пока пустой компонент на движке окна `view`.
  /// Компонент загрузит встроенный текст QML через `setData()`, а затем
  /// создаст корневой объект через `createWithInitialProperties()`.
  /// Использование `view.engine()` связывает создание интерфейса
  /// с тем же движком QML, который обслуживает окно.
  auto component { QQmlComponent { view.engine( ) } };

  /// Подготовить пустой URL для вызовов `setData()` и `setContent()`.
  /// QML загружается из строки в памяти, поэтому адрес отдельного файла
  /// не указываем. Собственное имя компонента и базовый URL для разрешения
  /// относительных путей здесь явно не задаются.
  auto url { QUrl { } };

  /// Сохранить описание интерфейса QML в массиве байтов для передачи в `setData()`.
  /// Встроенный текст позволяет держать учебный пример в одном файле
  /// вместе с кодом создания и настройки интерфейса.
  /// Сырой строковый литерал `R"qml(...)qml"` сохраняет переводы строк,
  /// кавычки и обратные косые черты без экранирования средствами C++.
  auto data {
    QByteArray {
      R"qml(
        import QtQuick

        import Sample_0007 1.0

        Rectangle {

          id: main

          objectName: "main"

          required property StatusProvider statusProvider

          property string status: main.statusProvider.ready( )

          width: 800
          height: 600

          color: "#ffffff"

          Column {

            spacing: 10

            anchors.centerIn: parent

            Rectangle {

              id: button

              property bool spacePressed: false
              property bool mousePressed: mouseArea.pressed

              objectName: "button"

              anchors.horizontalCenter: parent.horizontalCenter

              width: 180
              height: 60

              radius: 6

              color: (mousePressed || spacePressed) ? "#aa2266" : "#2266aa"

              focus: true

              Text {

                anchors.centerIn: parent

                font.family: "Iosevka Aile Semibold"
                font.pixelSize: 24

                color: "#ffffff"

                text: "Нажать"
              }

              MouseArea {

                id: mouseArea

                anchors.fill: parent

                onPressed: main.status = main.statusProvider.mousePressed( )
              }

              Keys.onSpacePressed: ( ) => {
                button.spacePressed = true
                main.status = main.statusProvider.spacePressed( )
              }

              Keys.onReleased: (event) => {
                if (event.key == Qt.Key_Space) {
                  button.spacePressed = false
                  event.accepted = true
                }
              }
            }

            Text {

              anchors.horizontalCenter: parent.horizontalCenter

              font.family: "Iosevka Aile Semibold"
              font.pixelSize: 24

              color: "#444444"

              text: `Статус | ${main.status}`
            }
          }
        }
      )qml"
    }
  };

  /// Загрузить и скомпилировать встроенное описание QML из `data`.
  /// URL задаёт имя компонента и базу для разрешения относительных путей.
  /// В этом примере QML встроен в программу, а собственный адрес компонента
  /// и базовый путь к ресурсам не требуются, поэтому URL оставлен пустым.
  /// Создание экземпляра корневого объекта выполнить отдельно, чтобы задать
  /// обязательное свойство `statusProvider` через начальные значения.
  component.setData(data, url);

  /// Подготовить начальные значения свойств корневого объекта QML.
  /// `QVariantMap` сопоставляет имена свойств их значениям. Ключ `statusProvider`
  /// соответствует обязательному свойству, объявленному в корневом `Rectangle`.
  /// `QVariant::fromValue()` помещает указатель `StatusProvider*` в `QVariant`,
  /// сохраняя информацию о типе. Сам поставщик остаётся локальным объектом C++,
  /// к которому интерфейс будет обращаться через переданный указатель.
  auto initialProperties {
    QVariantMap {
      { "statusProvider", QVariant::fromValue(&statusProvider) }
    }
  };

  /// Создать корневой `Rectangle` и вложенные объекты из описания компонента,
  /// задав начальные свойства из `initialProperties`.
  /// Свойство `statusProvider` требуется уже при создании: оно объявлено
  /// обязательным и используется для получения исходного сообщения `ready()`.
  /// Контекст явно не передан, поэтому используется корневой контекст движка QML.
  auto root {
    component.createWithInitialProperties(initialProperties)
  };

  /// При отказе создания корневого объекта вывести ошибки компонента
  /// и завершить программу с кодом `1`, не запуская цикл событий.
  /// Ненулевой указатель подтверждает создание объекта, но не отсутствие
  /// всех ошибок присваивания свойств или выполнения выражений QML.
  if (root == nullptr) {
    qWarning( ) << component.errors( );
    return 1;
  }

  /// Задать объектное имя окна `window`, используемое Spix при поиске объектов.
  /// С него начинаются пути в тестах: `window/main` ведёт к корневому элементу,
  /// а `window/main/button` — к кнопке. Это свойство `QObject::objectName`,
  /// а не отображаемый заголовок окна.
  view.setObjectName("window");

  /// Установить созданный корневой объект QML как содержимое окна.
  /// Передать URL компонента, сам компонент и объект `root`, полученный
  /// через `createWithInitialProperties()` с заданным поставщиком сообщений.
  view.setContent(url, &component, root);

  /// Задать размер области содержимого окна 800×600 перед его показом.
  /// Эти размеры совпадают с шириной и высотой корневого `Rectangle` в QML.
  view.resize(800, 600);

  /// Показать окно с подготовленным интерфейсом QML.
  /// Обработку ввода и обновление интерфейса обеспечит цикл событий,
  /// который будет запущен ниже вызовом `app.exec()`.
  view.show( );


/// Включить управление интерфейсом через Spix только в тестовой сборке.
/// Макрос `BUILD_TESTING` задаётся в CMake при включении одноимённой опции.
/// В обычной сборке этот блок исключается препроцессором.
#if defined(BUILD_TESTING)

  /// Создать объект Spix для выполнения тестовых команд в интерфейсе Qt Quick.
  /// Он использует таймер Qt, чтобы обрабатывать команды в главном потоке.
  /// Локальный объект остаётся живым во время работы `app.exec()`;
  /// связь с XML-RPC-сервером будет настроена ниже.
  auto bot { spix::QtQmlBot { } };

  /// Создать XML-RPC-сервер Spix на TCP-порту `9000`.
  /// Через него внешние Ruby-клиенты передают команды управления интерфейсом.
  /// Номер порта должен совпадать с настройками подключения клиентов.
  /// Обработка запросов будет запущена ниже через `bot.runTestServer(server)`.
  auto server { spix::AnyRpcServer { 9000 } };

  /// Подключить сервер к исполнителю команд `bot` и запустить обработку запросов.
  /// Сервер работает в отдельном потоке и помещает команды в очередь.
  /// `bot` обрабатывает очередь в главном потоке по событиям таймера Qt
  /// после запуска цикла событий `app.exec()`.
  bot.runTestServer(server);
#endif

  /// Запустить главный цикл событий Qt для обработки ввода, таймеров
  /// и обновления интерфейса, включая выполнение команд Spix в тестовой сборке.
  /// Вызов возвращает управление после завершения цикла событий;
  /// его код завершения сохранить в `result` для возврата из `main`.
  auto result { app.exec( ) };

  /// Вернуть код завершения цикла событий Qt как код завершения программы.
  /// При выходе из `main` локальные объекты будут уничтожены в порядке,
  /// обратном порядку их создания.
  return result;
}

